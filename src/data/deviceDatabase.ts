/**
 * Utility to calculate battery runtime in hours
 */
export function calculateBatteryRuntimeHours(
  capacityWh: number,
  healthPercent: number,
  reservePercent: number,
  powerDrawWatts: number,
  environmentalFactor: number = 1.0 // e.g. 1.0 = normal, 0.9 = cold (-10%), etc.
): number {
  if (powerDrawWatts <= 0 || capacityWh <= 0) return 0;
  const healthFraction = Math.max(0.1, Math.min(1.0, healthPercent / 100));
  const reserveFraction = Math.max(0, Math.min(0.5, reservePercent / 100));
  const usableCapacityWh = capacityWh * healthFraction * (1 - reserveFraction) * environmentalFactor;
  return usableCapacityWh / powerDrawWatts;
}

/**
 * Utility to format hours into human readable "X hours Y minutes"
 */
export function formatHoursMinutes(totalHours: number): string {
  if (isNaN(totalHours) || totalHours <= 0) return '0 mins';
  const hrs = Math.floor(totalHours);
  const mins = Math.round((totalHours - hrs) * 60);

  if (hrs === 0) {
    return `${mins} min${mins === 1 ? '' : 's'}`;
  }
  if (mins === 0) {
    return `${hrs} hour${hrs === 1 ? '' : 's'}`;
  }
  return `${hrs}h ${mins}m`;
}

/**
 * Convert mAh and Voltage to Wh
 */
export function mahToWh(mah: number, voltage: number): number {
  return (mah * voltage) / 1000;
}

/**
 * Convert Wh and Voltage to mAh
 */
export function whToMah(wh: number, voltage: number): number {
  return (wh * 1000) / voltage;
}
